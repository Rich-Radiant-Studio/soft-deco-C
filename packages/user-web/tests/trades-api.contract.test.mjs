import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
const api = await readFile(new URL('../src/api/trades.ts', import.meta.url), 'utf8')
const view = await readFile(new URL('../src/views/Transactions.vue', import.meta.url), 'utf8')
assert.ok(api.includes("'/app/trade/getList?'"), 'trade endpoint path is correct')
assert.ok(api.includes("method: 'POST'"), 'trade list uses POST')
assert.ok(api.includes("'Content-Type': 'application/x-www-form-urlencoded'"), 'form-urlencoded content type is set')
assert.ok(api.includes('pageNum: String(pageNum), pageSize: String(pageSize)'), 'pagination is query params')
assert.ok(api.includes('pageSize > 20'), 'page size is capped at 20')
assert.ok(api.includes('getCustomerAuthState') && api.includes('Authorization:'), 'formal customer auth is required')
assert.ok(api.includes('payload?.success === true || payload?.code === 0 || payload?.code === 200'), 'business response is checked')
assert.ok(api.includes('Number.isSafeInteger(item.demandId)'), 'unsafe int64 IDs are rejected')
assert.ok(api.includes("'Transaction response page structure is not recognized.'"), 'unknown pagination wrappers are errors, not empty')
assert.ok(view.includes('record.statusText || record.status'), 'backend statusText takes precedence')
assert.ok(view.includes('record.amount, record.currency'), 'amount and currency are displayed')
assert.ok(view.includes('sequence') && view.includes('getTradeList(pageNum.value,pageSize.value)'), 'page requests are race guarded and paged')
assert.ok(!view.includes('TXN-789123') && !view.includes('Download Transaction Report'), 'mock transactions and fake download removed')
assert.ok(!view.includes('All Types') && !view.includes('startDate'), 'unsupported global filters removed')
console.log('PASS trade request/page contract assertions')
